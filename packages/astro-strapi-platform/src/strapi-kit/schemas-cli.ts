/**
 * Writes the platform schemas into the Strapi app in the current directory.
 * Runs before `strapi develop` and `strapi build` (the app's pre-scripts), so
 * a version bump of this package is all it takes to update them.
 *
 * Called through `require(…).main()`, not an npm `bin`: in the platform repo
 * `dist/` does not exist yet at `npm ci`, and npm then links no bin at all.
 *
 *   src/**                       generated, committed, never edited by hand
 *   schema-extensions/<name>.json  the site's additions (info, new attributes)
 *   platform-schemas.json      manifest of what was generated last
 */
import fs from "node:fs";
import path from "node:path";
import { buildSchemas, planSync, SchemaError, type FileMap, type Manifest } from "./schemas";

const MANIFEST = "platform-schemas.json";
const PLATFORM_DIR = path.join(__dirname, "..", "..", "schemas");

function readTree(root: string, dir = ""): FileMap {
  const files: FileMap = {};
  for (const entry of fs.readdirSync(path.join(root, dir), { withFileTypes: true })) {
    const rel = dir ? `${dir}/${entry.name}` : entry.name;
    if (entry.isDirectory()) Object.assign(files, readTree(root, rel));
    else files[rel] = fs.readFileSync(path.join(root, rel), "utf8");
  }
  return files;
}

const readIfExists = (file: string) =>
  fs.existsSync(file) ? fs.readFileSync(file, "utf8") : undefined;

function parseJson(file: string): unknown {
  try {
    return JSON.parse(fs.readFileSync(file, "utf8"));
  } catch (error) {
    throw new SchemaError([`${file}: ${(error as Error).message}`]);
  }
}

/** Removes `dir` and its parents up to `stop` while they are empty. */
function pruneEmpty(dir: string, stop: string): void {
  while (dir !== stop && fs.existsSync(dir) && fs.readdirSync(dir).length === 0) {
    fs.rmdirSync(dir);
    dir = path.dirname(dir);
  }
}

export function syncSchemas(appDir: string, platformDir = PLATFORM_DIR): { written: number; removed: number } {
  const src = path.join(appDir, "src");
  const platform = readTree(platformDir);

  const blocksDir = path.join(src, "components", "blocks");
  const siteBlocks = fs.existsSync(blocksDir)
    ? fs
        .readdirSync(blocksDir)
        .filter((f) => f.endsWith(".json") && !(`components/blocks/${f}` in platform))
        .map((f) => f.slice(0, -".json".length))
    : [];

  const extensionsDir = path.join(appDir, "schema-extensions");
  const extensions: Record<string, unknown> = {};
  if (fs.existsSync(extensionsDir)) {
    for (const f of fs.readdirSync(extensionsDir).filter((f) => f.endsWith(".json"))) {
      extensions[f.slice(0, -".json".length)] = parseJson(path.join(extensionsDir, f));
    }
  }

  const generated = buildSchemas({ platform, siteBlocks, extensions });
  const manifestFile = path.join(appDir, MANIFEST);
  const manifest = fs.existsSync(manifestFile) ? (parseJson(manifestFile) as { files: Manifest }).files : {};

  const disk: Record<string, string | undefined> = {};
  for (const rel of new Set([...Object.keys(generated), ...Object.keys(manifest)])) {
    disk[rel] = readIfExists(path.join(src, rel));
  }

  const plan = planSync(manifest, disk, generated);
  for (const [rel, content] of Object.entries(plan.write)) {
    fs.mkdirSync(path.dirname(path.join(src, rel)), { recursive: true });
    fs.writeFileSync(path.join(src, rel), content);
  }
  for (const rel of plan.remove) {
    fs.rmSync(path.join(src, rel));
    pruneEmpty(path.dirname(path.join(src, rel)), src);
  }
  fs.writeFileSync(
    manifestFile,
    `${JSON.stringify({ $comment: "Generated by platform-schemas. Do not edit.", files: plan.manifest }, null, 2)}\n`
  );
  return { written: Object.keys(plan.write).length, removed: plan.remove.length };
}

export function main(): void {
  try {
    const { written, removed } = syncSchemas(process.cwd());
    console.log(`platform-schemas: ${written} written, ${removed} removed.`);
  } catch (error) {
    if (error instanceof SchemaError) {
      console.error("platform-schemas: refusing to write platform schemas:");
      for (const problem of error.problems) console.error(`  - ${problem}`);
    } else {
      console.error(error);
    }
    process.exit(1);
  }
}
